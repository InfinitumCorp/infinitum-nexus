#!/usr/bin/env node
/**
 * Builds the Cloudflare Worker entry (wrangler.jsonc main): dist/entry.mjs embeds every file in
 * public/ and hands the rest to src/server/worker.ts. public/ itself is not changed.
 *   node apps/spectre/scripts/build-cloudflare.mjs
 *   node apps/spectre/scripts/build-cloudflare.mjs --assets apps/spectre/live-ui --out apps/spectre/dist/entry.mjs
 * The default directory is public/ (the repo UI). Production id.cumuluscloud.app must use --assets
 * live-ui, the byte snapshot of the pages that host serves today. Do not deploy the default build:
 * it would replace those pages.
 */
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
export const MIME = {
  ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8",
  ".svg": "image/svg+xml", ".json": "application/json", ".webmanifest": "application/manifest+json",
  ".png": "image/png", ".ico": "image/x-icon", ".txt": "text/plain; charset=utf-8", ".woff2": "font/woff2",
};

/** Every file under `dir`, keyed by its site path (`/index.html`). Bodies are base64. */
export function filesFromAssets(dir) {
  const files = {};
  const walk = (current) => {
    for (const name of readdirSync(current)) {
      const p = join(current, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (!name.startsWith(".")) files[`/${relative(dir, p).split("\\").join("/")}`] = { type: MIME[extname(p)] ?? "application/octet-stream", body: readFileSync(p).toString("base64") };
    }
  };
  walk(dir);
  return files;
}

export function workerEntrySource(files) {
  return `// Generated by scripts/build-cloudflare.mjs. Do not edit.
import { handleRequest } from "../src/server/worker.ts";
export { NexusStore } from "../src/server/worker.ts";
const FILES = ${JSON.stringify(files)};
export default { fetch: (request, env, ctx) => handleRequest(request, env, ctx, FILES) };
`;
}

const isDirect = Boolean(process.argv[1]?.endsWith("build-cloudflare.mjs"));
if (isDirect) {
  const assetFlag = process.argv.indexOf("--assets");
  const pub = assetFlag >= 0 ? process.argv[assetFlag + 1] : join(app, "public");
  if (!pub) throw new Error("--assets needs a directory");
  const outFlag = process.argv.indexOf("--out");
  const out = outFlag >= 0 ? process.argv[outFlag + 1] : join(app, "dist/entry.mjs");
  const files = filesFromAssets(pub);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, workerEntrySource(files));
  console.log(`Built ${out} with ${Object.keys(files).length} public files from ${pub}`);
}
