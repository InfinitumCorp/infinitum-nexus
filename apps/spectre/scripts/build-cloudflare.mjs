#!/usr/bin/env node
/**
 * Builds the Cloudflare Worker entry (wrangler.jsonc main): dist/entry.mjs embeds every file in
 * public/ and hands the rest to src/server/worker.ts. public/ itself is not changed.
 *   node apps/spectre/scripts/build-cloudflare.mjs && (cd apps/spectre && npx wrangler deploy)
 */
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const pub = join(app, "public");
const MIME = {
  ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8",
  ".svg": "image/svg+xml", ".json": "application/json", ".webmanifest": "application/manifest+json",
  ".png": "image/png", ".ico": "image/x-icon", ".txt": "text/plain; charset=utf-8", ".woff2": "font/woff2",
};
const files = {};
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files[`/${relative(pub, p).split("\\").join("/")}`] = { type: MIME[extname(p)] ?? "application/octet-stream", body: readFileSync(p).toString("base64") };
  }
};
walk(pub);
mkdirSync(join(app, "dist"), { recursive: true });
writeFileSync(join(app, "dist/entry.mjs"), `// Generated by scripts/build-cloudflare.mjs. Do not edit.
import { handleRequest } from "../src/server/worker.ts";
export { NexusStore } from "../src/server/worker.ts";
const FILES = ${JSON.stringify(files)};
export default { fetch: (request, env, ctx) => handleRequest(request, env, ctx, FILES) };
`);
console.log(`Built dist/entry.mjs with ${Object.keys(files).length} public files`);
