/**
 * Copy the VEIL web app into the APK's assets as the offline Hub page, and
 * render launcher icons. Downloads, the service worker and the PWA manifest
 * stay out of the APK.
 */
import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { render } from "../../veil-web/scripts/brand-icon.js";
import { BLOCKED_HOSTS } from "../../veil/lib/blocklist.js";

const root = fileURLToPath(new URL("../", import.meta.url));
const web = fileURLToPath(new URL("../../veil-web/", import.meta.url));

execSync(`node "${web}scripts/build.js"`, { stdio: "inherit" });

const hub = `${root}src/main/assets/hub/`;
rmSync(hub, { recursive: true, force: true });
mkdirSync(`${hub}lib`, { recursive: true });
mkdirSync(`${hub}icons`, { recursive: true });
mkdirSync(`${hub}brand`, { recursive: true });
mkdirSync(`${hub}i18n`, { recursive: true });
for (const f of ["index.html", "app.js", "search.html", "search.js", "lib/trackers.js", "firm-suite.js", "firm-suite.css", "icons/icon-192.png", "brand/horizontal-white-bg.png",
  "i18n/i18n.js", "i18n/i18n.css", "i18n/start.js", "i18n/catalogs.js"]) {
  cpSync(`${web}public/${f}`, `${hub}${f}`);
}

const DENSITIES = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
for (const [d, px] of Object.entries(DENSITIES)) {
  const dir = `${root}src/main/res/mipmap-${d}/`;
  mkdirSync(dir, { recursive: true });
  // The checked-in icons carry the ™ (drawn by hand, #113): only render missing ones.
  if (!existsSync(`${dir}ic_launcher.png`)) writeFileSync(`${dir}ic_launcher.png`, render(px));
}
// Same blocklist as the extension (apps/veil/lib/blocklist.js).
const javaHosts = BLOCKED_HOSTS.map((h) => `        "${h}"`).join(",\n");
writeFileSync(`${root}src/main/java/app/infinitum/veil/browser/Blocklist.java`, `package app.infinitum.veil.browser;

import java.util.Arrays;
import java.util.Collections;
import java.util.List;

/**
 * Generated by scripts/sync-hub.js from apps/veil/lib/blocklist.js. Do not edit.
 * Ad networks, trackers and data brokers, curated by Infinitum Corporation.
 */
public final class Blocklist {
    private Blocklist() {}

    public static final List<String> HOSTS = Collections.unmodifiableList(Arrays.asList(
${javaHosts}
    ));

    /** True when host is a listed host or one of its subdomains. */
    public static boolean isBlocked(String host) {
        if (host == null) return false;
        String h = host.toLowerCase(java.util.Locale.ROOT);
        if (h.endsWith(".")) h = h.substring(0, h.length() - 1);
        if (h.isEmpty()) return false;
        for (String b : HOSTS) if (h.equals(b) || h.endsWith("." + b)) return true;
        return false;
    }
}
`);
console.log("hub synced, launcher icons rendered, blocklist generated");
