/**
 * Builds lib/region-blocks.js from a v2ray/Xray geosite.dat.
 *   node scripts/geosite-ru.js <geosite.dat> <release-tag>
 *
 * Source: re:filter (https://github.com/1andrevich/Re-filter-lists, MIT), the
 * geosite.dat asset of a tagged release. It lists domains blocked in Russia.
 * Only the `refilter` category is kept, and only domain and full-host rules;
 * keyword and regex rules are skipped. The list is used to explain a failed
 * page load. It never changes how traffic is routed.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const CATEGORY = "REFILTER";
const [, , datPath, tag] = process.argv;
if (!datPath || !tag) {
  console.error("usage: node scripts/geosite-ru.js <geosite.dat> <release-tag>");
  process.exit(2);
}

const buf = readFileSync(datPath);
const sha256 = createHash("sha256").update(buf).digest("hex");

function varint(b, at) {
  let value = 0;
  let mul = 1;
  for (;;) {
    const byte = b[at++];
    if (byte === undefined) throw new Error("truncated varint");
    value += (byte & 0x7f) * mul;
    if (byte < 0x80) return [value, at];
    mul *= 128;
  }
}

/** Yields [field, wireType, value] for one protobuf message. */
function* fields(b, start = 0, end = b.length) {
  let at = start;
  while (at < end) {
    let key;
    [key, at] = varint(b, at);
    const field = Math.floor(key / 8);
    const wire = key & 7;
    if (wire === 0) {
      let v;
      [v, at] = varint(b, at);
      yield [field, wire, v];
    } else if (wire === 2) {
      let len;
      [len, at] = varint(b, at);
      yield [field, wire, [at, at + len]];
      at += len;
    } else if (wire === 5) {
      at += 4;
    } else if (wire === 1) {
      at += 8;
    } else {
      throw new Error(`unsupported wire type ${wire}`);
    }
  }
}

const text = (range) => buf.toString("utf8", range[0], range[1]);
// Domain.Type: 0 Plain (keyword), 1 Regex, 2 Domain (and subdomains), 3 Full.
const hosts = new Set();
let found = false;
let skipped = 0;
for (const [field, , site] of fields(buf)) {
  if (field !== 1) continue;
  let code = "";
  const domains = [];
  for (const [f, , v] of fields(buf, site[0], site[1])) {
    if (f === 1) code = text(v).toUpperCase();
    else if (f === 2) domains.push(v);
  }
  if (code !== CATEGORY) continue;
  found = true;
  for (const d of domains) {
    let type = 0;
    let value = "";
    for (const [f, , v] of fields(buf, d[0], d[1])) {
      if (f === 1) type = v;
      else if (f === 2) value = text(v).toLowerCase();
    }
    if ((type === 2 || type === 3) && /^[a-z0-9.-]+\.[a-z0-9-]+$/.test(value)) hosts.add(value);
    else skipped++;
  }
}
if (!found) throw new Error(`category ${CATEGORY} not in ${datPath}`);

const list = [...hosts].sort();
const out = fileURLToPath(new URL("../lib/region-blocks.js", import.meta.url));
writeFileSync(out, `// Generated by scripts/geosite-ru.js. Do not edit by hand.
// Source: re:filter (1andrevich/Re-filter-lists, MIT) release ${tag}, geosite.dat category refilter
// geosite.dat sha256 ${sha256}
export const RU_BLOCKED_SOURCE = ${JSON.stringify({ release: tag, sha256, count: list.length })};
export const RU_BLOCKED = new Set(${JSON.stringify(list)});
`);
console.log(`wrote ${list.length} hosts (${skipped} keyword/regex rules skipped) to lib/region-blocks.js`);
