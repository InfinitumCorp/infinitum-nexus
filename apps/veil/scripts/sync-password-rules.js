/**
 * Regenerate lib/password-rules.js from the vendored MIT data in
 * third_party/password-manager-resources/password-rules.json.
 *   node scripts/sync-password-rules.js
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const src = fileURLToPath(new URL("../../../third_party/password-manager-resources/password-rules.json", import.meta.url));
const out = fileURLToPath(new URL("../lib/password-rules.js", import.meta.url));
const data = JSON.parse(readFileSync(src, "utf8"));
const rules = Object.fromEntries(Object.entries(data).map(([host, v]) => [host, v["password-rules"]]).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(out,
  "/*\n * Generated by scripts/sync-password-rules.js. Do not edit.\n" +
  " * Data: password-manager-resources quirks/password-rules.json\n" +
  " * Copyright 2020 - 2026 Apple Inc. MIT License (third_party/password-manager-resources/LICENSE.md).\n */\n" +
  `export const PASSWORD_RULES = Object.freeze(${JSON.stringify(rules, null, 0)});\n`);
console.log(`password-rules: ${Object.keys(rules).length} sites`);
