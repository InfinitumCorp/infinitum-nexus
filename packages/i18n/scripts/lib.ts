// Pure helpers for the translation script (tested in lib.test.ts).
type Catalog = Record<string, string>;

/** Pull the first JSON object out of a model reply (tolerates code fences and chatter). */
export function parseJsonObject(raw: string): Record<string, unknown> {
  const text = raw.replace(/<think>[\s\S]*?<\/think>/g, "");
  const start = text.indexOf("{");
  const end = text.lastIndexOf("}");
  if (start < 0 || end <= start) throw new Error("no JSON object in reply");
  return JSON.parse(text.slice(start, end + 1));
}

const placeholders = (s: string) => (s.match(/\{\w+\}|%\d*\$?[sd]/g) ?? []).sort().join("|");
const tags = (s: string) => (s.match(/<\/?[a-zA-Z][^>]*>/g) ?? []).map((t) => t.replace(/\s.*$/, "")).sort().join("|");

/** Keys whose translation is missing or broke a placeholder or HTML tag. */
export function findBadTranslations(source: Catalog, translated: Catalog): string[] {
  return Object.keys(source).filter((k) => {
    const t = translated[k];
    if (typeof t !== "string" || !t.trim()) return true;
    return placeholders(source[k]) !== placeholders(t) || tags(source[k]) !== tags(t);
  });
}

/** Android resource qualifier for a language. */
export function androidLocaleDir(code: string): string {
  if (code === "zh") return "values-zh-rCN";
  if (code === "pt") return "values-pt-rBR";
  return `values-${code}`;
}

/** Chrome _locales folder name for a language (Chrome has no bare zh/pt). */
export function chromeLocaleDir(code: string): string {
  if (code === "zh") return "zh_CN";
  if (code === "pt") return "pt_BR";
  return code;
}

const decodeXml = (s: string) => s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, "&");

/** Read translatable <string> entries from an Android strings.xml (values unescaped). */
export function readAndroidStrings(xml: string): Catalog {
  const out: Catalog = {};
  const re = /<string\s+([^>]*?)>([\s\S]*?)<\/string>/g;
  for (const m of xml.matchAll(re)) {
    const attrs = m[1];
    if (/translatable\s*=\s*"false"/.test(attrs)) continue;
    const name = /name\s*=\s*"([^"]+)"/.exec(attrs)?.[1];
    if (!name) continue;
    let v = m[2].trim();
    if (v.startsWith('"') && v.endsWith('"')) v = v.slice(1, -1);
    out[name] = decodeXml(v).replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/\\n/g, "\n").replace(/\\@/g, "@").replace(/\\\?/g, "?");
  }
  return out;
}

/** Escape a value for Android strings.xml. */
export function escapeAndroid(v: string): string {
  let s = v.replace(/\\/g, "\\\\").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/'/g, "\\'").replace(/"/g, '\\"').replace(/\n/g, "\\n");
  if (s.startsWith("@") || s.startsWith("?")) s = "\\" + s;
  return s;
}

export function writeAndroidStrings(c: Catalog): string {
  const lines = Object.entries(c).map(([k, v]) => `    <string name="${k}">${escapeAndroid(v)}</string>`);
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by @infinitum/i18n from values/strings.xml. Do not edit; re-run the translate script. -->\n<resources>\n${lines.join("\n")}\n</resources>\n`;
}
