#!/usr/bin/env bash
# Dependency audit, license inventory, and a secrets scan for this tree.
# Writes evidence when a report directory is given. Exits non-zero on high/critical
# advisories or a likely secret. Does not deploy or publish.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"
report="${1:-}"
if [[ -n "$report" ]]; then
  mkdir -p "$report"
fi

audit_file="$(mktemp)"
license_file="$(mktemp)"
secrets_file="$(mktemp)"
trap 'rm -f "$audit_file" "$license_file" "$secrets_file"' EXIT

set +e
pnpm audit --json >"$audit_file"
audit_status=$?
set -e
# pnpm 10 exits 1 when advisories exist. Any other failure is a broken audit.
if [[ "$audit_status" -gt 1 ]]; then
  echo "pnpm audit failed to run (exit $audit_status)" >&2
  cat "$audit_file" >&2
  exit "$audit_status"
fi

node --input-type=module - "$audit_file" <<'NODE'
import { readFileSync } from "node:fs";
const report = JSON.parse(readFileSync(process.argv[2], "utf8"));
const advisories = report.advisories ?? {};
const list = Array.isArray(report.vulnerabilities) ? report.vulnerabilities : Object.values(advisories);
const bad = list.filter((item) => ["high", "critical"].includes(String(item.severity).toLowerCase()));
const meta = report.metadata?.vulnerabilities ?? {};
console.log(`dependency audit: info=${meta.info ?? 0} low=${meta.low ?? 0} moderate=${meta.moderate ?? 0} high=${meta.high ?? 0} critical=${meta.critical ?? 0}`);
if (bad.length) {
  for (const item of bad) console.error(`- ${item.severity}: ${item.module_name ?? item.name ?? "unknown"} ${item.title ?? item.url ?? ""}`);
  process.exitCode = 1;
}
NODE
audit_policy=$?

set +e
pnpm licenses list --json >"$license_file"
license_status=$?
set -e
if [[ "$license_status" -ne 0 ]]; then
  echo "pnpm licenses list failed (exit $license_status)" >&2
  exit "$license_status"
fi
node --input-type=module - "$license_file" <<'NODE'
import { readFileSync } from "node:fs";
const tree = JSON.parse(readFileSync(process.argv[2], "utf8"));
const counts = new Map();
for (const [license, packages] of Object.entries(tree)) {
  counts.set(license, Array.isArray(packages) ? packages.length : 0);
}
const summary = [...counts.entries()].sort((a, b) => a[0].localeCompare(b[0]));
console.log(`license groups: ${summary.map(([license, count]) => `${license}=${count}`).join(", ") || "(none)"}`);
NODE

# High-confidence token shapes only. Patterns are built so this file does not contain a match.
node --input-type=module - "$root" "$secrets_file" <<'NODE'
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
const root = process.argv[2];
const out = process.argv[3];
const skip = new Set(["node_modules", "artifacts", ".git", "dist"]);
const patterns = [
  { name: "private-key", re: new RegExp("-----BEGIN (?:RSA |OPENSSH |EC |DSA )?PRIVATE KEY-----") },
  { name: "aws-access-key", re: /AKIA[0-9A-Z]{16}/ },
  { name: "github-token", re: /ghp_[A-Za-z0-9]{36}/ },
  { name: "github-pat", re: /github_pat_[A-Za-z0-9_]{20,}/ },
  { name: "slack-token", re: /xox[baprs]-[A-Za-z0-9-]{10,}/ },
  { name: "stripe-live", re: /sk_live_[A-Za-z0-9]{16,}/ },
  { name: "google-api", re: /AIza[0-9A-Za-z\-_]{35}/ },
];
const hits = [];
function walk(dir) {
  for (const name of readdirSync(dir)) {
    if (skip.has(name)) continue;
    const path = join(dir, name);
    const stat = statSync(path);
    if (stat.isDirectory()) { walk(path); continue; }
    if (stat.size > 2_000_000) continue;
    let text;
    try { text = readFileSync(path, "utf8"); } catch { continue; }
    if (text.includes("\0")) continue;
    const rel = relative(root, path);
    const lines = text.split("\n");
    for (const pattern of patterns) {
      lines.forEach((line, index) => {
        if (pattern.re.test(line)) hits.push(`${rel}:${index + 1}:${pattern.name}`);
      });
    }
  }
}
walk(root);
writeFileSync(out, hits.join("\n"));
if (hits.length) {
  console.error(`secrets scan: ${hits.length} hit(s)`);
  for (const hit of hits) console.error(`- ${hit}`);
  process.exit(1);
}
console.log("secrets scan: 0 hits");
NODE

if [[ -n "$report" ]]; then
  cp "$audit_file" "$report/pnpm-audit.json"
  cp "$license_file" "$report/licenses.json"
  cp "$secrets_file" "$report/secrets.txt"
  if [[ ! -s "$report/secrets.txt" ]]; then
    echo "0 hits" >"$report/secrets.txt"
  fi
  {
    echo "# Labyrinth security evidence"
    echo
    echo "Generated by \`bash scripts/labyrinth-security.sh $report\`."
    echo "Re-run the same command to refresh. CI runs the script with no report directory and fails on high or critical advisories or a secret hit."
    echo
    echo "- Audit JSON: pnpm-audit.json"
    echo "- License inventory: licenses.json"
    echo "- Secrets scan: secrets.txt"
  } >"$report/README.md"
fi

if [[ "$audit_policy" -ne 0 ]]; then
  echo "dependency audit failed the high/critical policy" >&2
  exit 1
fi
echo "security checks passed"
